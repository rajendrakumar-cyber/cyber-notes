# Parse traces
traces_dir = "/home/white/white/Music/PICO-CTF/challenge/traces"
pts = []
traces = []

print("Parsing trace files...")
for i in range(100):
    filepath = os.path.join(traces_dir, f"trace{i:02d}.txt")
    with open(filepath, "r") as f:
        lines = f.readlines()
        
    pt_line = lines[0].strip()
    trace_line = lines[1].strip()
    
    pt_hex = pt_line.split("Plaintext:")[1].strip()
    pt = list(bytes.fromhex(pt_hex))
    
    trace_str = trace_line.split("Power trace:")[1].strip()
    trace = eval(trace_str)
    
    pts.append(pt)
    traces.append(trace)

pts = np.array(pts, dtype=np.int32)
traces = np.array(traces, dtype=np.float64)

D, T = traces.shape
print(f"Loaded {D} traces of shape {pts.shape} and trace length {T}")

# Mean center Y (traces)
Y_mean = np.mean(traces, axis=0, keepdims=True)
Y_centered = traces - Y_mean
Y_std = np.sqrt(np.sum(Y_centered**2, axis=0))
Y_std[Y_std == 0] = 1.0

recovered_key = bytearray(16)

# Perform CPA with Windowing
for byte_idx in range(16):
    H = np.zeros((D, 256), dtype=np.float64)
    for k in range(256):
        state = pts[:, byte_idx] ^ k
        sbox_out = np.array([Sbox[s] for s in state], dtype=np.int32)
        H[:, k] = HW[sbox_out]
        
    H_mean = np.mean(H, axis=0, keepdims=True)
    H_centered = H - H_mean
    H_std = np.sqrt(np.sum(H_centered**2, axis=0))
    H_std[H_std == 0] = 1.0
    
    num = np.dot(H_centered.T, Y_centered)
    den = np.outer(H_std, Y_std)
    corr = np.abs(num / den)
    
    # Restrict to window around correct_times[byte_idx]
    t_center = correct_times[byte_idx]
    window = corr[:, t_center - 2 : t_center + 3]  # Width of 5 samples
    
    # For each candidate, find the max correlation inside the window
    max_corr_per_candidate = np.max(window, axis=1)
    
    sorted_candidates = np.argsort(max_corr_per_candidate)[::-1]
    best_candidate = sorted_candidates[0]
    second_best = sorted_candidates[1]
    
    best_val = max_corr_per_candidate[best_candidate]
    second_val = max_corr_per_candidate[second_best]
    peak_offset = np.argmax(window[best_candidate]) - 2
    
    print(f"Byte {byte_idx:2d}: Best candidate 0x{best_candidate:02x} (corr: {best_val:.4f} at t={t_center + peak_offset}), Second: 0x{second_best:02x} (corr: {second_val:.4f}), Ratio: {best_val/second_val:.2f}")
    recovered_key[byte_idx] = best_candidate

key_hex = recovered_key.hex()
print("\nReconstructed Key:", key_hex)
print("Flag format: picoCTF{" + key_hex + "}")
