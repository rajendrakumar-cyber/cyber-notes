HW = np.array([bin(x).count('1') for x in range(256)], dtype=np.float64)

# Load data
data = np.load("/home/white/.gemini/antigravity-cli/brain/6cb6672e-f3b1-4e76-b9bc-5990778be2dd/scratch/traces.npz", allow_pickle=True)
pts_raw = data["pts"]
pts = np.array([list(bytes(p).ljust(16, b"\x00")) for p in pts_raw], dtype=np.int32)
traces = data["traces"].astype(np.float64)

D, T = traces.shape
print(f"Loaded {D} traces of shape {pts.shape} and trace length {T}")

# Mean center Y (traces)
Y_mean = np.mean(traces, axis=0, keepdims=True)
Y_centered = traces - Y_mean
Y_std = np.sqrt(np.sum(Y_centered**2, axis=0))

# Replace zero std with 1 to avoid divide by zero (should not happen for real trace noise)
Y_std[Y_std == 0] = 1.0

recovered_key = bytearray(16)

# Perform CPA for each of the 16 key bytes
for byte_idx in range(16):
    # Compute Hamming weight matrix for all 256 candidates
    # shape of H: (D, 256)
    H = np.zeros((D, 256), dtype=np.float64)
    for k in range(256):
        # pt byte XOR k, Sbox, Hamming weight
        state = pts[:, byte_idx] ^ k
        sbox_out = np.array([Sbox[s] for s in state], dtype=np.int32)
        H[:, k] = HW[sbox_out]
        
    # Mean center H
    H_mean = np.mean(H, axis=0, keepdims=True)
    H_centered = H - H_mean
    H_std = np.sqrt(np.sum(H_centered**2, axis=0))
    H_std[H_std == 0] = 1.0
    
    # Numerator of Pearson correlation: shape (256, T)
    num = np.dot(H_centered.T, Y_centered)
    
    # Denominator: shape (256, T)
    den = np.outer(H_std, Y_std)
    
    # Correlation matrix
    corr = np.abs(num / den)
    
    # For each candidate, find the max correlation over all time points
    max_corr_per_candidate = np.max(corr, axis=1) # shape (256,)
    
    # Find the top 2 candidates
    sorted_candidates = np.argsort(max_corr_per_candidate)[::-1]
    best_candidate = sorted_candidates[0]
    second_best = sorted_candidates[1]
    
    best_val = max_corr_per_candidate[best_candidate]
    second_val = max_corr_per_candidate[second_best]
    
    # Index of peak time point for best candidate
    peak_time = np.argmax(corr[best_candidate])
    
    print(f"Byte {byte_idx:2d}: Best candidate 0x{best_candidate:02x} (corr: {best_val:.4f} at t={peak_time}), Second: 0x{second_best:02x} (corr: {second_val:.4f}), Ratio: {best_val/second_val:.2f}")
    
    recovered_key[byte_idx] = best_candidate

key_hex = recovered_key.hex()
